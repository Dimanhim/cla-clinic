    public static function setRelation($leadId, $appointmentId)
    {
        $model = new Relation();
        $model->lead_id = $leadId;
        $model->appointment_id = $appointmentId;
        if(!$model->save()) {
            file_put_contents('--relation-errors-log.txt', date('d.m.Y H:i') . ' - set - ' . print_r($model->errors, true)."\n", FILE_APPEND);
        }
    }

    public static function deleteRelation($leadId, $appointmentId)
    {
        $model = Relation::findOne(['lead_id' => $leadId, 'appointment_id' => $appointmentId]);
        if(!$model) return false;
        if(!$model->delete()) {
            file_put_contents('--relation-errors-log.txt', date('d.m.Y H:i') . ' - delete - ' . print_r($model->errors, true)."\n", FILE_APPEND);
        }
    }

    public static function deleteLead($leadId)
    {
        $models = Relation::findAll(['lead_id' => $leadId]);
        if(!$models) return false;

        foreach($models as $model) {
            $str = "lead_id = " . $model->lead_id . " appointment_id = " . $model->appointment_id;
            if($model->delete()) {
                file_put_contents('--problems-log.txt', date('d.m.Y H:i') . ' - deleted - ' . print_r($str, true)."\n", FILE_APPEND);
            }
            else {
                file_put_contents('--problems-errors-log.txt', date('d.m.Y H:i') . ' - error - ' . print_r($model->errors, true)."\n", FILE_APPEND);
            }
        }

        return count($models);
    }

